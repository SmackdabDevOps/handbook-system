import * as fs from 'fs';
import * as path from 'path';
import { execSync } from 'child_process';

export interface HuskyOptions {
  projectRoot: string;
  validatorsPath: string;  // e.g., 'scripts/validation'
}

/**
 * Install Husky and configure git hooks
 */
export function installHusky(options: HuskyOptions): boolean {
  try {
    console.log('📦 Installing Husky...');

    // 1. Check if git repo exists
    if (!fs.existsSync(path.join(options.projectRoot, '.git'))) {
      console.log('⚠️  No .git directory found. Initializing git...');
      execSync('git init', { cwd: options.projectRoot, stdio: 'inherit' });
    }

    // 2. Install husky as dev dependency (if not already installed)
    const packageJson = JSON.parse(
      fs.readFileSync(path.join(options.projectRoot, 'package.json'), 'utf-8')
    );

    if (!packageJson.devDependencies?.husky) {
      console.log('  Installing husky package...');
      execSync('npm install husky --save-dev', { cwd: options.projectRoot, stdio: 'inherit' });
    }

    // 3. Initialize husky
    console.log('  Initializing husky...');
    execSync('npx husky install', { cwd: options.projectRoot, stdio: 'inherit' });

    // 4. Add prepare script if not present
    if (!packageJson.scripts?.prepare?.includes('husky')) {
      packageJson.scripts = packageJson.scripts || {};
      packageJson.scripts.prepare = 'husky install';
      fs.writeFileSync(
        path.join(options.projectRoot, 'package.json'),
        JSON.stringify(packageJson, null, 2)
      );
    }

    // 5. Create pre-commit hook
    const preCommitPath = path.join(options.projectRoot, '.husky', 'pre-commit');
    const preCommitContent = generatePreCommitHook(options.validatorsPath);
    fs.writeFileSync(preCommitPath, preCommitContent, { mode: 0o755 });

    // 6. Create commit-msg hook
    const commitMsgPath = path.join(options.projectRoot, '.husky', 'commit-msg');
    const commitMsgContent = generateCommitMsgHook(options.validatorsPath);
    fs.writeFileSync(commitMsgPath, commitMsgContent, { mode: 0o755 });

    console.log('✅ Husky hooks installed');
    return true;

  } catch (error) {
    console.error('❌ Failed to install Husky:', error);
    return false;
  }
}

function generatePreCommitHook(validatorsPath: string): string {
  return `#!/bin/sh
# =============================================================================
# Pre-Commit Hook - Code Quality, Test Coverage & TDD Enforcement
# =============================================================================
# Generated by @smackdab/handbook-system
# See handbook/cicd/PRE_COMMIT_HOOKS.md for documentation
# =============================================================================

echo "🔍 Running pre-commit checks..."
echo ""

# Step 1: Lint & Format
echo "📝 Step 1/3: Linting & formatting staged files..."
npx lint-staged
if [ $? -ne 0 ]; then
  echo "❌ COMMIT BLOCKED - Lint/format errors"
  exit 1
fi
echo "✅ Lint & format passed"

# Step 2: Test Coverage
echo "🧪 Step 2/3: Checking test coverage for staged files..."
npx ts-node ${validatorsPath}/check-staged-coverage.ts
if [ $? -ne 0 ]; then
  echo "❌ COMMIT BLOCKED - Staged files below 90% coverage"
  exit 1
fi
echo "✅ Staged file coverage passed"

# Step 3: TDD Validator Check
echo "📋 Step 3/3: Checking TDD validator status..."
npx ts-node ${validatorsPath}/commit-guard.ts
if [ $? -ne 0 ]; then
  echo "❌ COMMIT BLOCKED - TDD validation failed"
  exit 1
fi

echo "✅ All pre-commit checks passed"
`;
}

function generateCommitMsgHook(validatorsPath: string): string {
  return `#!/bin/sh
# =============================================================================
# Commit Message Hook - Validation Freshness Check
# =============================================================================
# Generated by @smackdab/handbook-system
# =============================================================================

npx ts-node ${validatorsPath}/check-registry-freshness.ts
if [ $? -ne 0 ]; then
  echo "❌ COMMIT BLOCKED - Validation results are stale"
  echo "Run: npm run validation:quick"
  exit 1
fi
`;
}

/**
 * Check if Husky is already installed
 */
export function isHuskyInstalled(projectRoot: string): boolean {
  return fs.existsSync(path.join(projectRoot, '.husky'));
}
